import math

from geom import arc, fill, line, mark
from wave1 import card

W = 6


def base():
    return [fill(arc(16, 32, 6, 0, 360)), line(arc(16, 32, 17, -48, 48), W), line(arc(16, 32, 28, -46, 46), W * 0.72)]


def fade():
    return [fill(arc(16, 32, 6, 0, 360)), line(arc(16, 32, 17, -50, 50), W),
            line(arc(16, 32, 28, -34, 34), W * 0.72), line(arc(16, 32, 38, -20, 20), W * 0.5)]


def broken():
    items = [fill(arc(16, 32, 6, 0, 360)), line(arc(16, 32, 17, -50, 50), W)]
    for a0, a1 in ((-48, -24), (-10, 10), (24, 48)):
        items.append(line(arc(16, 32, 28, a0, a1), W * 0.72))
    return items


def rotate(items, deg):
    c, s = math.cos(math.radians(deg)), math.sin(math.radians(deg))
    return [(k, [(x * c - y * s, x * s + y * c) for x, y in pts], w) for k, pts, w in items]


def rise():
    return rotate(base(), -30)


def embrace():
    return [fill(arc(26, 32, 6, 0, 360)), line(arc(26, 32, 16, -120, 120), W), line(arc(26, 32, 27, -55, 55), W * 0.72)]


def source():
    return [fill(arc(16, 32, 10, 0, 360)), line(arc(16, 32, 20, -46, 46), W), line(arc(16, 32, 30, -42, 42), W * 0.72)]


VARIANTS = {"2a": base, "2b": fade, "2c": broken, "2d": rise, "2e": embrace, "2f": source}


def variant_svg(cid, key, in_circle):
    return mark(VARIANTS[key](), in_circle)


